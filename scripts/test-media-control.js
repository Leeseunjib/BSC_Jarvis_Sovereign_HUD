'use strict';
const fs=require('fs'),os=require('os'),path=require('path'),assert=require('assert/strict');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'jarvis-media-'));
process.env.JARVIS_DATA_DIR=temp;process.env.JARVIS_DISABLE_EXTERNAL_HUB='1';
const {ButlerEngine,WindowsHands}=require(process.env.JARVIS_TEST_VERIFIED_RUNTIME==='1'?'./butler-engine.verified':'./butler-engine');
const {VoiceSessions}=require('./voice-session');
const {createMediaController}=require('./media-control');
(async()=>{
  const engine=new ButlerEngine();
  let fallbackCalls=0;
  const fallback=createMediaController(async()=>{throw Error('Native failed');},async()=>{fallbackCalls++;return{ok:true,state:'Paused',verified:true};});
  assert.equal((await fallback({action:'pause'})).state,'Paused');assert.equal(fallbackCalls,1);
  const noTarget=createMediaController(async()=>({ok:true,state:'none'}),async()=>({ok:true,state:'none',verified:true}));
  assert.equal((await noTarget({action:'pause'})).state,'none');
  for(const phrase of ['음악 꺼줘','음악 좀 꺼 줘','노래를 멈춰줘','유튜브 음악 꺼줘','유튜브 닫아줘']) assert.equal(engine.parseIntent(phrase).intent,'stopMusic',phrase);
  assert.notEqual(engine.parseIntent('음악 꺼주지 마').intent,'stopMusic');
  assert.notEqual(engine.parseIntent('꺼줘').intent,'stopMusic');
  let now=1000;const sessions=new VoiceSessions(engine,()=>now);
  assert.equal(sessions.accept('test','음악 꺼줘'),true);
  assert.equal(sessions.accept('other','카톡 친구한테 안녕이라고 보내'),false);
  assert.equal(sessions.accept('other','꺼줘'),false);
  const opened=[];const originalOpen=WindowsHands.openMediaUrl;
  WindowsHands.openMediaUrl=async url=>{opened.push(url);return{processId:123};};
  engine.searchYouTube=async()=>[{index:1,title:'시험 음악',url:'https://www.youtube.com/watch?v=test',id:'test'}];
  await engine.execute('클래식 음악 틀어줘',true);
  assert.equal(opened.length,1);assert.equal(engine.hasMediaContext(),true);
  now+=600000;assert.equal(sessions.accept('new-session','꺼줘'),true,'이어 듣기가 끝나도 음악 문맥에서 정지해야 합니다');
  const calls=[];
  engine.mediaControl=async request=>{calls.push(request);return{ok:true,verified:true,changed:true,state:'Paused',source:'chrome.exe'};};
  const stopped=await engine.execute('꺼줘',true);
  assert.equal(stopped.intent,'stopMusic');assert.equal(stopped.media.state,'Paused');assert.equal(calls[0].action,'pause');
  const restored=new ButlerEngine();assert.equal(restored.hasMediaContext(),true,'서버를 다시 시작해도 문맥이 남아야 합니다');
  const resumed=await engine.execute('다시 틀어줘',false);assert.equal(resumed.intent,'resumeMusic');assert.equal(calls.length,1,'시험 모드에서는 실제 제어를 하면 안 됩니다');
  engine.mediaControl=async()=>({ok:true,verified:true,changed:false,state:'none'});
  const missing=await engine.execute('음악 꺼줘',true);assert.equal(missing.hudColor,'amber');assert(!missing.spoken.includes('멈췄습니다'));assert.equal(engine.hasMediaContext(),false);
  const missingResume=await engine.execute('음악 다시 틀어줘',true);assert.equal(missingResume.hudColor,'amber');assert(!missingResume.spoken.includes('재생했습니다'));
  engine.mediaControl=async()=>({ok:true,verified:true,state:'Playing'});
  await assert.rejects(engine.execute('음악 꺼줘',true),/확인하지 못했습니다/);
  engine.mediaControl=async()=>({ok:true,verified:false,state:'Playing'});
  await assert.rejects(engine.execute('음악 꺼줘',true),/확인하지 못했습니다/);
  engine.mediaControl=async()=>{throw Error('앱 응답 실패');};
  await assert.rejects(engine.execute('음악 꺼줘',true),/앱 응답 실패/);
  WindowsHands.openMediaUrl=originalOpen;
  console.log('PASS: 정지 표현·부정 표현·호출어 예외 범위·재생 문맥 유지·정지 검증·시험 모드·실패 시 성공 오표시 방지');
})().catch(err=>{console.error(err);process.exitCode=1;}).finally(()=>{
  const resolved=fs.realpathSync(temp);if(path.dirname(resolved)===fs.realpathSync(os.tmpdir())&&path.basename(resolved).startsWith('jarvis-media-'))fs.rmSync(resolved,{recursive:true,force:true});
});
