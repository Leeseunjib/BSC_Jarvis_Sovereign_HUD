'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
process.env.JARVIS_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'jarvis-research-'));
process.env.JARVIS_DISABLE_EXTERNAL_HUB='1';
const r=require('./web-research');
const {ButlerEngine}=require('./butler-engine');
(async()=>{
  const engine=new ButlerEngine();
  assert.equal(engine.parseIntent('REA 기술 알아?').intent,'research');
  assert.equal(engine.parseIntent('벡터 검색에 대해 설명해').intent,'research');
  assert.equal(engine.parseIntent('자비스 몇 시야').intent,'clock');
  assert.equal(engine.parseIntent('음악 꺼줘').intent,'stopMusic');
  assert.equal(r.queryFor('REA 기술 알아?'),'REA 기술');
  assert.equal(r.queryFor('REA에 대해 조사해줘'),'REA');
  const duck='<a class="result__a" href="//duckduckgo.com/l/?uddg=https%3A%2F%2Fexample.org%2Frea">REA &amp; tools</a><a class="result__snippet">REA 원문 설명입니다.</a>';
  assert.deepEqual(r.parseDuck(duck),[{title:'REA & tools',url:'https://example.org/rea',snippet:'REA 원문 설명입니다.'}]);
  const rss='<rss><item><title>REA docs</title><link>https://example.org/docs</link><description>REA 검색 설명</description></item></rss>';
  let calls=0;
  const fallback=await r.searchWeb('REA',async()=>({text:++calls===1?'captcha':rss}));
  assert.equal(fallback.provider,'Bing');assert.equal(calls,2);assert.equal(fallback.results.length,1);
  calls=0;const irrelevant=await r.searchWeb('REA',async()=>({text:++calls===1?duck.replace(/REA/g,'unrelated'):rss}));assert.equal(irrelevant.provider,'Bing');assert.equal(calls,2,'무관한 검색 결과도 대체 검색이 필요합니다');
  const dedup=await r.searchWeb('REA',async()=>({text:duck+duck}));assert.equal(dedup.results.length,1);
  const report=await r.research('REA 기술 알아?',{readPages:false,search:async()=>fallback});
  assert.equal(report.status,'ready');assert(report.summary.includes('[1]'));assert.equal(report.sections[0].sourceId,report.sources[0].id);assert.equal(report.sources[0].readStatus,'검색 미리보기');assert(report.note.includes('약어'));
  const failed=await r.research('없는 주제 알아?',{readPages:false,search:q=>r.searchWeb(q,async()=>{throw Error('offline');})});
  assert.equal(failed.status,'unavailable');assert.equal(failed.sources.length,0);assert.equal(failed.summary,'');assert.equal(failed.errors.length,2);
  for(const url of ['file:///C:/secret','http://127.0.0.1/','http://localhost/','https://x.local/','https://user:pw@example.org/','https://example.org:7788/'])assert.equal(r.safeUrl(url),null);
  for(const ip of ['127.0.0.1','10.1.2.3','192.168.1.2','172.16.0.1','169.254.1.1','::1','fd00::1'])assert.equal(r.publicAddress(ip),false,ip);
  assert(r.publicAddress('8.8.8.8'));
  console.log('PASS: 질문 분류·실제 검색 파싱·검색 엔진 대체·중복 제거·출처 연결·검색 실패·공개 출처 제한');
})().catch(e=>{console.error(e);process.exitCode=1;});
